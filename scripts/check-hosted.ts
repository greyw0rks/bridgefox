import assert from "node:assert/strict";
import { randomBytes, createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import JSZip from "jszip";
import { setDefaultResultOrder } from "node:dns";
import { DEMO } from "../src/lib/demo";
setDefaultResultOrder("ipv4first");
const base = process.env.BRIDGEFOX_TEST_URL ?? "https://bridgefox.vercel.app";
const checks: string[] = [];
const json = async (path: string, body?: unknown) => {
  const response = await fetch(`${base}${path}`, { method: body === undefined ? "GET" : "POST", headers: { ...(body === undefined ? {} : { "Content-Type": "application/json", Origin: base }) }, body: body === undefined ? undefined : JSON.stringify(body) });
  const data = await response.json();
  assert.equal(response.status, 200, `${path}: ${data.error ?? response.status}`);
  return data;
};
const status = await json("/api/status");
assert.equal(status.directUploads, true);
assert.equal(status.accessRequired, false);
assert.equal(status.aiAccessRequired, true);
checks.push("Public local studio uses shared storage; AI access remains protected");
const archive = new JSZip();
for (const file of DEMO.files) archive.file(file.path, file.content);
const asset = randomBytes(6 * 1024 * 1024);
archive.file("preserved-large-asset.bin", asset);
archive.file("large-source.js", "/*" + " source stays intact ".repeat(150000) + "*/");
const upload = await archive.generateAsync({ type: "uint8array", compression: "DEFLATE" });
assert.ok(upload.length > 4.5 * 1024 * 1024);
const { uploadUrl } = await json("/api/upload", {});
const stored = await fetch(uploadUrl, { method: "POST", headers: { "Content-Type": "application/zip" }, body: upload as BodyInit });
assert.equal(stored.status, 200);
const { storageId } = await stored.json();
const imported = await json("/api/import", { storageId, name: "hosted-preservation.zip" });
assert.ok(imported.projectId);
assert.equal(imported.project.files.find((file: { path: string }) => file.path === "preserved-large-asset.bin").content, "");
checks.push("A ZIP above the serverless request limit uploads directly and imports through Convex");
const migrated = await fetch(`${base}/api/migrate`, { method: "POST", headers: { "Content-Type": "application/json", Origin: base }, body: JSON.stringify({ projectId: imported.projectId, mode: "local" }) });
assert.equal(migrated.status, 200);
const events = (await migrated.text()).trim().split("\n").filter(Boolean).map(line => JSON.parse(line));
const result = events.find(event => event.type === "result")?.result;
assert.equal(result?.status, "candidate");
assert.equal(result?.mode, "local");
checks.push("A separate migration request loads the stored project and streams a real local result");
const output = await json("/api/export", { projectId: imported.projectId, patches: result.patches, format: "addon" });
const download = await fetch(output.downloadUrl);
assert.equal(download.status, 200);
const bytes = new Uint8Array(await download.arrayBuffer());
const zip = await JSZip.loadAsync(bytes);
assert.deepEqual(await zip.file("preserved-large-asset.bin")!.async("uint8array"), new Uint8Array(asset));
assert.equal(await zip.file("large-source.js")!.async("string"), "/*" + " source stays intact ".repeat(150000) + "*/");
checks.push("Export downloads from Convex and preserves the exact binary asset and large source");
const denied = await fetch(`${base}/api/migrate`, { method: "POST", headers: { "Content-Type": "application/json", Origin: base }, body: JSON.stringify({ projectId: imported.projectId, mode: "otari" }) });
assert.equal(denied.status, 401);
checks.push("Anonymous Otari execution is rejected before any paid gateway call");
const foreign = await fetch(`${base}/api/upload`, { method: "POST", headers: { Origin: "https://other.example" } });
assert.equal(foreign.status, 403);
checks.push("Foreign browser origins cannot create upload URLs");
await mkdir("docs/evidence", { recursive: true });
await writeFile("docs/evidence/hosted-checks-2026-11-10.json", JSON.stringify({ testedAt: new Date().toISOString(), base, checks, uploadBytes: upload.length, exportedBytes: bytes.length, binarySha256: createHash("sha256").update(asset).digest("hex"), liveOtariCalls: 0 }, null, 2) + "\n");
console.log(checks.map(check => `PASS ${check}`).join("\n"));
